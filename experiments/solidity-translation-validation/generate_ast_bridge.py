#!/usr/bin/env python3
"""Quote exact nodes from pinned irOptimizedAst; no semantic rewrites."""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
AST_HASH = "60059226825f5eea534dad2f8a705fa81bd1924011a308f428181dc694d9f92c"
YUL_HASH = "42533dc6d3b36a3aac988012250647bf21fa1be3908e0b104524cd6636913851"
BODY_PATH = ["subObjects", 0, "code", "block", "statements", 0,
             "statements", 2, "body", "statements", 0, "body", "statements"]


def get(node, path):
    for part in path:
        node = node[part]
    return node


def quote_json(value):
    if isinstance(value, str):
        return "(.str " + json.dumps(value) + ")"
    if isinstance(value, list):
        return "(.arr #[" + ", ".join(map(quote_json, value)) + "])"
    if isinstance(value, dict):
        return "(Lean.Json.mkObj [" + ", ".join(
            "(" + json.dumps(k) + ", " + quote_json(v) + ")"
            for k, v in sorted(value.items())) + "])"
    raise ValueError("unhandled JSON value; refusing to guess a quotation")


def expr(node):
    kind = node["nodeType"]
    if kind == "YulIdentifier":
        return "(.Var " + json.dumps(node["name"]) + ")"
    if kind == "YulFunctionCall":
        name = node["functionName"]["name"]
        arities = {"mul": 2, "div": 2, "eq": 2, "or": 2, "iszero": 1, "shl": 2,
                   "mstore": 2, "revert": 2, "return": 2}
        if name not in arities or len(node["arguments"]) != arities[name]:
            raise ValueError("unsupported expression in selected source node")
        return "(.Call (.inl ." + name.upper() + ") [" + ", ".join(
            expr(arg) for arg in node["arguments"]) + "])"
    if kind == "YulLiteral" and node["kind"] == "number" and node["type"] == "":
        raw = node["value"]
        value = int(raw, 16 if raw.startswith("0x") else 10)
        if not 0 <= value < 2**256:
            raise ValueError("out-of-word Yul numeral")
        return "(.Lit (EvmYul.UInt256.ofNat " + str(value) + "))"
    raise ValueError("unsupported expression in selected source node")


def stmt(node):
    kind = node["nodeType"]
    if kind == "YulVariableDeclaration" and len(node["variables"]) == 1:
        return "(.Let [" + json.dumps(node["variables"][0]["name"]) + "] (some " + expr(node["value"]) + "))"
    if kind == "YulIf":
        return "(.If " + expr(node["condition"]) + " [" + ", ".join(
            stmt(child) for child in node["body"]["statements"]) + "])"
    if kind == "YulExpressionStatement":
        return "(.ExprStmtCall " + expr(node["expression"]) + ")"
    raise ValueError("unsupported statement in selected source nodes")


def render():
    ast_bytes = (HERE / "MulDivDown.optimized-ast.json").read_bytes()
    yul = (HERE / "MulDivDown.optimized.yul").read_bytes()
    if hashlib.sha256(ast_bytes).hexdigest() != AST_HASH or hashlib.sha256(yul).hexdigest() != YUL_HASH:
        raise ValueError("optimized compiler artifacts differ from the pinned capture")
    ast = json.loads(ast_bytes)
    body = get(ast, BODY_PATH)
    if body[5]["variables"][0]["name"] != "product":
        raise ValueError("product binding changed")
    if body[8]["expression"]["functionName"]["name"] != "mstore":
        raise ValueError("return-word store changed")
    selections = {"Product": BODY_PATH + [5, "value"],
                  "Quotient": BODY_PATH + [8, "expression", "arguments", 1]}
    lines = ["-- Generated by generate_ast_bridge.py; do not edit.",
             "import TranslationValidationAstDecoder", "",
             "namespace SolidityTranslationValidation.AstBridge", ""]
    for name, path in selections.items():
        node = get(ast, path)
        start, length, source = map(int, node["nativeSrc"].split(":"))
        if source != 0 or start < 0 or length <= 0 or start + length > len(yul):
            raise ValueError("invalid optimized-Yul source span")
        lines += ["-- JSON path: " + json.dumps(path),
                  "-- nativeSrc: " + node["nativeSrc"] + "; bytes: " + yul[start:start+length].decode(),
                  "def captured" + name + "Json : Lean.Json := " + quote_json(node),
                  "def captured" + name + "Expr : EvmYul.Yul.Ast.Expr := " + expr(node),
                  "theorem decode" + name + " : decodeExpr 8 captured" + name + "Json =",
                  "    .ok captured" + name + "Expr := by rfl", ""]
    declaration = body[5]
    lines += ["-- JSON path: " + json.dumps(BODY_PATH + [5]),
              "def capturedProductDeclarationJson : Lean.Json := " + quote_json(declaration),
              'def capturedProductDeclaration : EvmYul.Yul.Ast.Stmt := .Let ["product"] (some capturedProductExpr)',
              "theorem decodeProductDeclaration : decodeDeclaration 8 capturedProductDeclarationJson =",
              "    .ok capturedProductDeclaration := by rfl", ""]
    for name, index in [("OverflowGuard", 6), ("DenominatorGuard", 7), ("ReturnStore", 8), ("Return", 9)]:
        node = body[index]
        lines += ["-- JSON path: " + json.dumps(BODY_PATH + [index]),
                  "def captured" + name + "Json : Lean.Json := " + quote_json(node),
                  "def captured" + name + " : EvmYul.Yul.Ast.Stmt := " + stmt(node),
                  "theorem decode" + name + " : decodeStmt 20 captured" + name + "Json =",
                  "    .ok captured" + name + " := by rfl", ""]
        if node["nodeType"] == "YulIf":
            lines += ["def captured" + name + "Condition : EvmYul.Yul.Ast.Expr := " + expr(node["condition"]), ""]
    lines += ["-- Contiguous body slice [5:8], assembled as a block; not the dispatcher.",
              "def capturedGuardedPrefix : EvmYul.Yul.Ast.Stmt :=",
              "  .Block [capturedProductDeclaration, capturedOverflowGuard, capturedDenominatorGuard]", ""]
    lines += ["-- Contiguous body slice [5:10], including the actual store and return.",
              "def capturedArithmeticBody : EvmYul.Yul.Ast.Stmt :=",
              "  .Block [capturedProductDeclaration, capturedOverflowGuard, capturedDenominatorGuard,",
              "    capturedReturnStore, capturedReturn]", ""]
    lines += ["end SolidityTranslationValidation.AstBridge", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = HERE / "CapturedNodes.lean"
    rendered = render()
    if args.check:
        if output.read_text() != rendered:
            raise SystemExit("captured AST-node quotation differs")
    else:
        output.write_text(rendered)
    print("verified captured AST quotations" if args.check else "generated captured AST quotations")


if __name__ == "__main__":
    main()
