#!/usr/bin/env python3
"""Quote the real runtime dispatcher nodes, keeping the memoryguard extension explicit."""
import argparse
import json
from pathlib import Path
import generate_ast_bridge as base

HERE = Path(__file__).resolve().parent
RUNTIME_PATH = ["subObjects", 0, "code", "block", "statements", 0]


def expr(node):
    if node["nodeType"] == "YulFunctionCall":
        name = node["functionName"]["name"]
        arities = {"mul": 2, "div": 2, "eq": 2, "or": 2, "iszero": 1, "shl": 2,
                   "mstore": 2, "revert": 2, "return": 2, "calldataload": 1,
                   "calldatasize": 0, "callvalue": 0, "lt": 2, "slt": 2, "shr": 2,
                   "add": 2, "not": 1}
        if name not in arities or len(node["arguments"]) != arities[name]:
            raise ValueError("unsupported dispatcher expression")
        return "(.Call (.inl ." + name.upper() + ") [" + ", ".join(map(expr, node["arguments"])) + "])"
    return base.expr(node)


def stmt(node):
    kind = node["nodeType"]
    if kind == "YulVariableDeclaration" and len(node["variables"]) == 1:
        return "(.Let [" + json.dumps(node["variables"][0]["name"]) + "] (some " + expr(node["value"]) + "))"
    if kind == "YulIf":
        return "(.If " + expr(node["condition"]) + " [" + ", ".join(map(stmt, node["body"]["statements"])) + "])"
    if kind == "YulBlock":
        return "(.Block [" + ", ".join(map(stmt, node["statements"])) + "])"
    if kind == "YulExpressionStatement":
        return "(.ExprStmtCall " + expr(node["expression"]) + ")"
    raise ValueError("unsupported dispatcher statement")


def render():
    base.render()  # both pinned optimized artifact hashes
    ast = json.loads((HERE / "MulDivDown.optimized-ast.json").read_text())
    body = base.get(ast, base.BODY_PATH)
    nodes = [("FreeMemoryStore", RUNTIME_PATH + ["statements", 1]),
             ("CalldataGate", RUNTIME_PATH + ["statements", 2]),
             ("Fallback", RUNTIME_PATH + ["statements", 3]),
             ("SelectorGate", RUNTIME_PATH + ["statements", 2, "body", "statements", 0])]
    nodes += [(name, base.BODY_PATH + [index]) for name, index in
              [("ValueGuard", 0), ("LengthGuard", 1), ("LoadX", 2), ("LoadY", 3), ("LoadD", 4)]]
    nodes += [("FunctionBody", base.BODY_PATH[:-1])]
    lines = ["-- Generated by generate_dispatcher_bridge.py; no manual dispatcher transcription.",
             "import TranslationValidationDispatcherDecoder", "import TranslationValidationMemoryGuardExtension",
             "namespace SolidityTranslationValidation.AstBridge.Dispatcher", "set_option maxRecDepth 10000"]
    for name, path in nodes:
        node = base.get(ast, path)
        lines += ["-- JSON path: " + json.dumps(path) + "; nativeSrc: " + node["nativeSrc"],
                  f"def captured{name}Json : Lean.Json := " + base.quote_json(node),
                  f"def captured{name} : EvmYul.Yul.Ast.Stmt := " + stmt(node),
                  f"theorem decode{name} : decodeStmt 40 captured{name}Json = .ok captured{name} := by rfl"]
        if node["nodeType"] == "YulIf":
            lines += [f"def captured{name}Condition : EvmYul.Yul.Ast.Expr := " + expr(node["condition"])]
    lines += ["-- The complete runtime's inner block: memoryguard plus all three remaining statements.",
              "def capturedRuntime : MemoryGuard.Statement := .block [",
              '  .memoryguardDeclaration "_1" (EvmYul.UInt256.ofNat 128),',
              "  .native capturedFreeMemoryStore, .native capturedCalldataGate, .native capturedFallback]",
              "def capturedRuntimeJson : Lean.Json := " + base.quote_json(base.get(ast, RUNTIME_PATH)),
              "theorem decodeCapturedRuntime : decodeRuntime 40 capturedRuntimeJson = .ok capturedRuntime := by rfl",
              "def capturedLoads : EvmYul.Yul.Ast.Stmt := .Block [capturedLoadX, capturedLoadY, capturedLoadD]",
              *["#print axioms decode" + name for name, _ in nodes],
              "#print axioms decodeCapturedRuntime",
              "end SolidityTranslationValidation.AstBridge.Dispatcher", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = HERE / "DispatcherNodes.lean"
    expected = render()
    if args.check:
        if path.read_text() != expected:
            raise SystemExit("dispatcher quotation differs")
    else:
        path.write_text(expected)
    print("verified dispatcher quotations" if args.check else "generated dispatcher quotations")


if __name__ == "__main__":
    main()
