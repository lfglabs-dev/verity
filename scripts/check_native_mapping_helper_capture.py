#!/usr/bin/env python3
"""Regenerate pinned mapping-helper capture and authenticate the proved bytecode/decoder prefix."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

SCRIPT = Path(__file__).resolve()
REPO = SCRIPT.parent.parent
WORKSPACE = REPO
HERE = REPO / "artifacts/native-mapping-helper"
EXPORT = REPO / "scripts/solidity_differential/mapping_helper_export.lean.txt"
SOLC_HASHES = {
    'd40adc6f9fdbb22a97d32a02fa05688bf2ee7886affc48c9851b0afd4a726b39',
    '0a2829292697dda542e4e365bb63fbd6d3ed51537140222a880ab760cffa7746',
}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def encoded(value):
    return (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sysroot = Path(os.environ['LEAN_SYSROOT'])
    solc = REPO / '.lake/solidity-import/solc-0.8.34'
    assert sha(solc.read_bytes()) in SOLC_HASHES, 'unrecognized solc SHA-256'
    version = subprocess.check_output([str(solc), '--version'], text=True).strip()
    assert '0.8.34+commit.80d5c536' in version, version
    subprocess.run(['lake', 'build', 'Compiler.CodegenCommon', 'Compiler.Yul.PrettyPrint'],
                   cwd=REPO, check=True, capture_output=True, timeout=180)
    export = HERE / '.export-current.yul'
    try:
        subprocess.run(['lake', 'env', str(sysroot / 'bin/lean'), '--run', str(EXPORT), str(export)],
                       cwd=REPO, check=True, capture_output=True, timeout=120)
        source = export.read_bytes()
    finally:
        export.unlink(missing_ok=True)
    files = {'MappingHelper.yul': source}
    programs = {}
    for enabled in (False, True):
        name = 'optimized' if enabled else 'unoptimized'
        request = {'language': 'Yul', 'sources': {'MappingHelper.yul': {'content': source.decode()}},
                   'settings': {'evmVersion': 'osaka', 'optimizer': {'enabled': enabled, 'runs': 200},
                                'outputSelection': {'*': {'*': ['evm.bytecode.object', 'evm.bytecode.opcodes', 'evm.assembly']}}}}
        process = subprocess.run([str(solc), '--standard-json'], input=encoded(request),
                                 capture_output=True, check=True, timeout=60)
        output = json.loads(process.stdout)
        errors = [e for e in output.get('errors', []) if e['severity'] == 'error']
        assert not errors, errors
        files[name + '.input.json'] = encoded(request)
        files[name + '.output.json'] = encoded(output)
        bytecode = output['contracts']['MappingHelper.yul']['MappingHelper']['evm']['bytecode']
        programs[name] = bytes.fromhex(bytecode['object'])
    lean = 'import Compiler.Proofs.IRGeneration.NativeMappingStorageExecution\n\n'
    lean += 'namespace Compiler.Proofs.IRGeneration.CapturedMappingHelper\nopen EvmYul\n\n'
    for name, code in programs.items():
        lean += '/-- Actual pinned solc output of the exported Verity helper; regenerated by capture.py. -/\n'
        lean += 'def ' + name + ' : ByteArray := ⟨#[' + ', '.join(f'0x{x:02x}' for x in code) + ']⟩\n\n'
    lean += 'end Compiler.Proofs.IRGeneration.CapturedMappingHelper\n'
    files['CapturedMappingHelper.lean'] = lean.encode()
    files['DecodeProof.lean'] = (lean + (HERE / 'DecodeProof.lean.tail').read_text()).encode()
    proof = REPO / 'Compiler/Proofs/IRGeneration/NativeCapturedMappingHelper.lean'
    assert proof.read_bytes().startswith(files['DecodeProof.lean']), 'proof bytecode/decoder prefix differs from actual compiler capture'
    manifest = {'scope': 'compiler-output capture only; no whole-function or source-bytecode equivalence claimed',
                'compilerVersion': version, 'compilerSha256': sha(solc.read_bytes()),
                'inputs': {str(p.relative_to(WORKSPACE)): sha(p.read_bytes()) for p in
                           (EXPORT, SCRIPT, HERE / 'DecodeProof.lean.tail',
                            REPO / 'Compiler/CodegenCommon.lean', REPO / 'Compiler/Yul/Ast.lean',
                            REPO / 'Compiler/Yul/PrettyPrint.lean', REPO / 'lake-manifest.json',
                            REPO / 'lean-toolchain')},
                'files': {n: sha(b) for n, b in files.items()},
                'bytecodeSizes': {n: len(b) for n, b in programs.items()}}
    files['manifest.json'] = encoded(manifest)
    for name, data in files.items():
        path = HERE / name
        if args.check:
            assert path.read_bytes() == data, 'stale capture: ' + name
        else:
            path.write_bytes(data)
    print(('verified' if args.check else 'captured'), manifest['bytecodeSizes'])

if __name__ == '__main__':
    main()
